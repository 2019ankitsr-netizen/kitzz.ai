import soundfile as sf, numpy as np, json, sys
from kokoro import KPipeline
p = KPipeline(lang_code='h')
L = [
"पार्ट टू। चित्रगुप्त जी ने, अपनी कलम क्यों रख दी थी?",
"रावण पर जीत के बाद, अयोध्या में, श्री राम के राजतिलक की तैयारी थी।",
"गुरु वशिष्ठ के शिष्यों ने, सभी देवताओं को न्योता भेजा। पर चित्रगुप्त जी का नाम, छूट गया।",
"इस भूल से आहत होकर, चित्रगुप्त जी ने, अपनी कलम रख दी।",
"और यमलोक में, कर्मों का हिसाब ही रुक गया! कौन स्वर्ग जाए, कौन नर्क, कोई तय नहीं कर पा रहा था।",
"तब श्री राम, गुरु वशिष्ठ के साथ, चित्रगुप्त जी के पास गए, और भूल की क्षमा माँगी।",
"प्रभु के कहने पर, चित्रगुप्त जी ने, कलम की पूजा की, और फिर से लिखना शुरू किया।",
"मान्यता है, तभी से कायस्थ परिवार, दिवाली पूजा के बाद कलम रख देते हैं, और यम द्वितीया पर, कलम-दवात पूजा के बाद ही, फिर उठाते हैं।",
"कल ये पूजा है। ये कहानी उस दोस्त को भेजिए, जो कल कलम उठाएगा। और ऐसी ही कहानियों के लिए, फॉलो कीजिए।",
]
voice = sys.argv[1]; sp = float(sys.argv[2])
durs = []
for i, t in enumerate(L):
    a = np.concatenate([np.asarray(r[2]) for r in p(t, voice=voice, speed=sp)])
    sf.write(f'v{i}.wav', a, 24000); durs.append(len(a) / 24000)
json.dump(durs, open('durs.json', 'w')); print([round(d, 2) for d in durs], round(sum(durs), 1))
